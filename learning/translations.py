def get_translation(key: str, language: str = 'en', **kwargs) -> str:
    """
    Get a translated string.

    Args:
        key: The translation key
        language: Language code ('en' or 'am')
        **kwargs: Values to format into the translation

    Returns:
        The translated string, formatted with any provided kwargs
    """
    # Ensure language is valid
    if language not in TRANSLATIONS:
        language = 'en'

    # Get the translation
    translated = TRANSLATIONS[language].get(key, TRANSLATIONS['en'].get(key, key))

    # Format with kwargs if provided
    if kwargs:
        try:
            return translated.format(**kwargs)
        except KeyError:
            return translated

    return translated


def get_all_translations(language: str = 'en') -> dict:
    """Get all translations for a language."""
    if language not in TRANSLATIONS:
        language = 'en'
    return TRANSLATIONS[language]
