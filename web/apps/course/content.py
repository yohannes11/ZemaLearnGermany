"""The course content as data, for the API: the same files the course page loads, so the web and the app
always teach the same thing. Both are generated by tools/course_content.py as `window.NAME = {json};`."""

import hashlib
import json
from functools import lru_cache
from pathlib import Path

from django.conf import settings

COURSE_FILE = "course/js/course-data.js"
AMHARIC_FILE = "course/js/course-am.js"


def _path(name: str) -> Path:
    return Path(settings.BASE_DIR) / "static" / name


@lru_cache(maxsize=8)
def _read(path: Path, mtime: float) -> tuple[dict, str]:
    """The script's data and its hash; cached until the file changes (`mtime` is part of the key)."""
    source = path.read_text(encoding="utf-8")
    data = json.loads(source[source.index("{") : source.rindex("}") + 1])
    return data, hashlib.sha256(source.encode()).hexdigest()


def load(name: str) -> tuple[dict, str]:
    path = _path(name)
    return _read(path, path.stat().st_mtime)


def course() -> tuple[dict, str]:
    """The course ({"units": [...]}) and its hash."""
    return load(COURSE_FILE)


def amharic() -> tuple[dict, str]:
    """Amharic meanings ({"words": {german: am}, "text": {english: am}}) and their hash."""
    return load(AMHARIC_FILE)
