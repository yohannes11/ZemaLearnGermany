// Copies the brand's design tokens from the web's design system (web/static/core/css/zema.css) into
// src/ui/theme/tokens.ts, so the site and the app share one palette. Run after changing zema.css:
//   npm run sync-tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(join(here, '../../web/static/core/css/zema.css'), 'utf8');

/** The colour custom properties declared directly in the block that starts with `selector {`. */
function colours(selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`zema.css has no "${selector}" block`);
  const body = css.slice(start, css.indexOf('}', start));
  const found = {};
  for (const [, name, value] of body.matchAll(/--([a-z0-9-]+):\s*(#[0-9a-fA-F]{3,8}|rgba?\([^)]*\))\s*;/g)) {
    found[name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())] = value;
  }
  return found;
}

const light = colours(':root');
const dark = { ...light, ...colours(':root[data-theme="dark"]') };
const out = `// Generated by scripts/sync-tokens.mjs from web/static/core/css/zema.css. Do not edit by hand.

export const light = ${JSON.stringify(light, null, 2)} as const;

export const dark: Record<keyof typeof light, string> = ${JSON.stringify(dark, null, 2)};

export type ColourName = keyof typeof light;
`;
writeFileSync(join(here, '../src/ui/theme/tokens.ts'), out);
console.log(`${Object.keys(light).length} colours -> src/ui/theme/tokens.ts`);
