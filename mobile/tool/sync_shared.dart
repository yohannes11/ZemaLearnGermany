// Copies what the app shares with the website, so both look and read the same:
//   - the colours of web/static/core/css/zema.css into lib/ui/tokens.dart;
//   - the interface translations web/locale/am.json into assets/locale/am.json.
// Run after changing either: dart run tool/sync_shared.dart
import 'dart:io';

final _root = File(Platform.script.toFilePath()).parent.parent.path;

Map<String, String> _colours(String css, String selector) {
  final start = css.indexOf('$selector {');
  if (start < 0) throw StateError('zema.css has no "$selector" block');
  final body = css.substring(start, css.indexOf('}', start));
  final found = <String, String>{};
  for (final m in RegExp(r'--([a-z0-9-]+):\s*(#[0-9a-fA-F]{3,8}|rgba?\([^)]*\))\s*;').allMatches(body)) {
    final name = m[1]!.replaceAllMapped(RegExp('-([a-z0-9])'), (c) => c[1]!.toUpperCase());
    found[name] = m[2]!;
  }
  return found;
}

String _dart(String value) {
  if (value.startsWith('#')) {
    var hex = value.substring(1);
    if (hex.length == 3) hex = hex.split('').map((c) => '$c$c').join();
    return 'Color(0xFF${hex.toUpperCase()})';
  }
  final parts = RegExp(r'[\d.]+').allMatches(value).map((m) => m[0]!).toList();
  final alpha = parts.length > 3 ? (double.parse(parts[3]) * 255).round() : 255;
  return 'Color.fromARGB($alpha, ${parts[0]}, ${parts[1]}, ${parts[2]})';
}

void main() {
  final css = File('$_root/../web/static/core/css/zema.css').readAsStringSync();
  final light = _colours(css, ':root');
  final dark = {...light, ..._colours(css, ':root[data-theme="dark"]')};
  final out = StringBuffer()
    ..writeln('// Generated by tool/sync_shared.dart from web/static/core/css/zema.css. Do not edit by hand.')
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln('class Tokens {')
    ..writeln('  const Tokens({${light.keys.map((k) => 'required this.$k').join(', ')}});')
    ..writeln('  final Color ${light.keys.join(', ')};')
    ..writeln('}')
    ..writeln()
    ..writeln('const lightTokens = Tokens(${light.entries.map((e) => '${e.key}: ${_dart(e.value)}').join(', ')});')
    ..writeln()
    ..writeln('const darkTokens = Tokens(${dark.entries.map((e) => '${e.key}: ${_dart(e.value)}').join(', ')});');
  File('$_root/lib/ui/tokens.dart').writeAsStringSync(out.toString());
  stdout.writeln('${light.length} colours -> lib/ui/tokens.dart');

  Directory('$_root/assets/locale').createSync(recursive: true);
  File('$_root/../web/locale/am.json').copySync('$_root/assets/locale/am.json');
  stdout.writeln('web/locale/am.json -> assets/locale/am.json');
}
